# Terjemahan ekspresi dari prioritas.cpp ke Python

# Ekspresi 1 & 2: Pembagian dan Perkalian
ekspresi_1 = 2 * 3 / 4
ekspresi_2 = 2 / 4 * 3

print("Hasil 2 * 3 / 4 di Python :", ekspresi_1)
print("Hasil 2 / 4 * 3 di Python :", ekspresi_2)

# Ekspresi 3: Menghitung variabel hitung
hitung = 10
